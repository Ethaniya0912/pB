            int[] flat = TriTableFlat;
            if (flat == null || flat.Length != 256 * 16)
            {
                Debug.LogError($"[MarchingCubes] TriTableFlat init 실패: " +
                               $"null={flat == null}, len={flat?.Length}");
                return t;  // 모두 0으로 채워진 배열 반환 (안전 장치)
            }
            for (int i = 0; i < 256; i++)
                for (int j = 0; j < 16; j++)
                    t[i, j] = flat[i * 16 + j];
            return t;
