    //   1. 8 corners의 SDF 샘플링 → isoLevel (보통 0) 기준 inside/outside
    //   2. 8 bits로 cube configuration 인덱스 (0~255)
    //   3. edgeTable → 어느 edge들이 iso surface와 교차하는지
    //   4. 교차 edge에서 linear interpolation으로 vertex 위치 계산
    //   5. triTable → 3개씩 묶어 triangle 생성
    //
    // Preview 용도 — Burst 미사용 (Editor 모드 single-call, 단일 Room 기준).
    // byte-identical: 신규 파일, 호출 전까지 영향 0.
    // ══════════════════════════════════════════════════════════════════════

    public struct MarchingCubesData
    {
        public Vector3[] vertices;
        public int[] triangles;
        public int triangleCount;
        public bool isEmpty => vertices == null || vertices.Length == 0;
    }

    public static class MarchingCubes
    {
        /// <summary>
        /// 3D SDF 그리드 → isoSurface mesh.
        /// sdfGrid[x, y, z] = 해당 셀 corner의 SDF 값.
        /// isoLevel 기준으로 polygonize (0.0 = 벽 경계).
        /// </summary>
        public static MarchingCubesData Generate(
            float[,,] sdfGrid,
            Vector3 origin,
            float voxelSize,
            float isoLevel = 0f)
        {
            if (sdfGrid == null)
                return default;

            int resX = sdfGrid.GetLength(0);
            int resY = sdfGrid.GetLength(1);
            int resZ = sdfGrid.GetLength(2);

            if (resX < 2 || resY < 2 || resZ < 2)
                return default;

            var verts = new List<Vector3>(1024);
            var tris = new List<int>(2048);

            // Pre-allocated edge vertex buffer (12 edges per cube)
            Vector3[] edgeVerts = new Vector3[12];

            for (int x = 0; x < resX - 1; x++)
            {
                for (int y = 0; y < resY - 1; y++)
                {
                    for (int z = 0; z < resZ - 1; z++)
                    {
                        ProcessCube(sdfGrid, x, y, z, origin, voxelSize,
                                    isoLevel, edgeVerts, verts, tris);
                    }
                }
            }

            return new MarchingCubesData
            {
                vertices = verts.ToArray(),
                triangles = tris.ToArray(),
                triangleCount = tris.Count / 3,
            };
        }

        private static void ProcessCube(
            float[,,] sdf, int x, int y, int z,
            Vector3 origin, float voxelSize, float isoLevel,
            Vector3[] edgeVerts, List<Vector3> verts, List<int> tris)
        {
            // 8 cube corner positions (world) + SDF values
            Vector3[] corners = new Vector3[8];
            float[] vals = new float[8];

            for (int c = 0; c < 8; c++)
            {
                int cx = x + CornerOffsets[c, 0];
                int cy = y + CornerOffsets[c, 1];
                int cz = z + CornerOffsets[c, 2];
                corners[c] = origin + new Vector3(cx, cy, cz) * voxelSize;
                vals[c] = sdf[cx, cy, cz];
            }

            // Cube configuration index
            int cubeIdx = 0;
            if (vals[0] < isoLevel) cubeIdx |= 1;
            if (vals[1] < isoLevel) cubeIdx |= 2;
            if (vals[2] < isoLevel) cubeIdx |= 4;
            if (vals[3] < isoLevel) cubeIdx |= 8;
            if (vals[4] < isoLevel) cubeIdx |= 16;
            if (vals[5] < isoLevel) cubeIdx |= 32;
            if (vals[6] < isoLevel) cubeIdx |= 64;
            if (vals[7] < isoLevel) cubeIdx |= 128;

            int edgeMask = EdgeTable[cubeIdx];
            if (edgeMask == 0) return;  // fully inside or outside

            // Compute vertex positions on 12 edges
            if ((edgeMask & 1) != 0) edgeVerts[0] = Interpolate(isoLevel, corners[0], corners[1], vals[0], vals[1]);
            if ((edgeMask & 2) != 0) edgeVerts[1] = Interpolate(isoLevel, corners[1], corners[2], vals[1], vals[2]);
            if ((edgeMask & 4) != 0) edgeVerts[2] = Interpolate(isoLevel, corners[2], corners[3], vals[2], vals[3]);
            if ((edgeMask & 8) != 0) edgeVerts[3] = Interpolate(isoLevel, corners[3], corners[0], vals[3], vals[0]);
            if ((edgeMask & 16) != 0) edgeVerts[4] = Interpolate(isoLevel, corners[4], corners[5], vals[4], vals[5]);
            if ((edgeMask & 32) != 0) edgeVerts[5] = Interpolate(isoLevel, corners[5], corners[6], vals[5], vals[6]);
            if ((edgeMask & 64) != 0) edgeVerts[6] = Interpolate(isoLevel, corners[6], corners[7], vals[6], vals[7]);
            if ((edgeMask & 128) != 0) edgeVerts[7] = Interpolate(isoLevel, corners[7], corners[4], vals[7], vals[4]);
            if ((edgeMask & 256) != 0) edgeVerts[8] = Interpolate(isoLevel, corners[0], corners[4], vals[0], vals[4]);
            if ((edgeMask & 512) != 0) edgeVerts[9] = Interpolate(isoLevel, corners[1], corners[5], vals[1], vals[5]);
            if ((edgeMask & 1024) != 0) edgeVerts[10] = Interpolate(isoLevel, corners[2], corners[6], vals[2], vals[6]);
            if ((edgeMask & 2048) != 0) edgeVerts[11] = Interpolate(isoLevel, corners[3], corners[7], vals[3], vals[7]);

            // Build triangles from triTable
            for (int i = 0; TriTable[cubeIdx, i] != -1; i += 3)
            {
                int baseIdx = verts.Count;
                verts.Add(edgeVerts[TriTable[cubeIdx, i]]);
                verts.Add(edgeVerts[TriTable[cubeIdx, i + 1]]);
                verts.Add(edgeVerts[TriTable[cubeIdx, i + 2]]);
                tris.Add(baseIdx);
                tris.Add(baseIdx + 1);
                tris.Add(baseIdx + 2);
            }
        }

        private static Vector3 Interpolate(float iso, Vector3 p1, Vector3 p2, float v1, float v2)
        {
            if (Mathf.Abs(iso - v1) < 1e-6f) return p1;
            if (Mathf.Abs(iso - v2) < 1e-6f) return p2;
            if (Mathf.Abs(v1 - v2) < 1e-6f) return p1;
            float t = (iso - v1) / (v2 - v1);
            return Vector3.Lerp(p1, p2, t);
        }

